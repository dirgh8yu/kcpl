/*
 * Customer portal language.
 *
 * KCPL's customers are Nepali businesses. The person who actually opens the
 * portal is often not the director who speaks English on the phone -- it is
 * the documentation clerk chasing a bill of lading, and freight is already a
 * jargon-heavy subject to meet in a second language.
 *
 * Three rules hold this together:
 *
 *   1. Completeness is a compile error, not a runtime surprise. The Nepali
 *      dictionary is typed against the English one, so a key added on one side
 *      and forgotten on the other fails `tsc` rather than rendering an English
 *      word in the middle of a Nepali sentence.
 *   2. Trade vocabulary stays as Nepali freight desks actually say it. "Bill
 *      of lading" is बिल अफ लेडिङ in a Kathmandu clearing office, not a coined
 *      Sanskritic translation nobody would recognise on a document.
 *   3. Data is never translated. A port name, a shipment reference, a
 *      filename and a staff note are records, and a portal that rewrites them
 *      is lying about what KCPL holds.
 */

export const portalLocales = ["en", "ne"] as const;
export type PortalLocale = (typeof portalLocales)[number];

export const portalLocaleLabels: Record<PortalLocale, string> = {
  en: "English",
  ne: "नेपाली",
};

/** Unknown or absent resolves to English, the language the portal shipped in. */
export function portalLocaleValue(value: unknown): PortalLocale {
  return portalLocales.includes(value as PortalLocale) ? value as PortalLocale : "en";
}

