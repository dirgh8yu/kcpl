const dictionaries: Record<PortalLocale, Record<PortalTextKey, string>> = { en, ne };

/**
 * One string, in the reader's language.
 *
 * `{name}` placeholders are substituted rather than concatenated, because
 * Nepali does not put the number where English does -- a sentence assembled
 * from fragments in English word order reads as broken Nepali.
 */
export function portalText(
  locale: PortalLocale,
  key: PortalTextKey,
  vars?: Record<string, string | number>,
): string {
  // A key that is not in either dictionary comes back as itself rather than as
  // `undefined`. Callers that build a key from runtime data -- a status, a
  // document type -- can then recognise the miss and fall back to a real
  // label, and the worst case on screen is a visible key rather than a blank.
  const template = dictionaries[locale]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
}

/** A bound translator, so a component reads `t("chrome.overview")`. */
export function portalTranslator(locale: PortalLocale) {
  return (key: PortalTextKey, vars?: Record<string, string | number>) => portalText(locale, key, vars);
}
